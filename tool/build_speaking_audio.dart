// Builds the examiner's audio for Speaking practice.
//
//   dart run tool/build_speaking_audio.dart           build the MP3s
//   dart run tool/build_speaking_audio.dart --readme  write the README
//
// Reads assets/speaking/content.json. For every line (questions and the
// examiner's other lines) it takes assets/speaking/audio/<id>.wav (from
// tool/generate_speaking_voices.py), trims the silence at both ends,
// normalises the loudness (two-pass EBU R128, linear) and writes one mono
// 64 kbps MP3: assets/speaking/mp3/<id>.mp3.
//
// Needs ffmpeg with libmp3lame on PATH (or set FFMPEG=/path/to/ffmpeg).
import 'dart:convert';
import 'dart:io';

import 'src/ffmpeg_tools.dart';

const _root = 'assets/speaking';
const _targetLoudness = -16.0;
const _truePeak = -1.5;
const _trim =
    'silenceremove=start_periods=1:start_silence=0.05:start_threshold=-50dB';

Future<void> main(List<String> args) async {
  final content =
      jsonDecode(File('$_root/content.json').readAsStringSync())
          as Map<String, dynamic>;
  final lines = speakingLines(content);
  if (args.contains('--readme')) {
    File('$_root/README.md').writeAsStringSync(_readme(lines));
    stdout.writeln('Wrote $_root/README.md');
    return;
  }

  await checkFfmpeg();
  final missing = [
    for (final l in lines)
      if (!File('$_root/audio/${l['id']}.wav').existsSync())
        'audio/${l['id']}.wav',
  ];
  if (missing.isNotEmpty) {
    fail('${missing.length} audio file(s) missing:\n  ${missing.join('\n  ')}');
  }
  Directory('$_root/mp3').createSync(recursive: true);
  for (final (i, line) in lines.indexed) {
    final id = line['id'] as String;
    final source = '$_root/audio/$id.wav';
    const trimBothEnds = '$_trim,areverse,$_trim,areverse';
    final m = await measureLoudness(
      source,
      trimBothEnds,
      target: _targetLoudness,
      truePeak: _truePeak,
    );
    await runFfmpeg([
      '-i',
      source,
      '-af',
      '$trimBothEnds,'
          '${loudnormFilter(m, target: _targetLoudness, truePeak: _truePeak)}',
      '-ar',
      '44100',
      '-ac',
      '1',
      '-c:a',
      'libmp3lame',
      '-b:a',
      '64k',
      '-map_metadata',
      '-1',
      '$_root/mp3/$id.mp3',
    ]);
    stdout.writeln('[${i + 1}/${lines.length}] mp3/$id.mp3');
  }
}

/// Every line with audio, in the app's order (SpeakingContent.allLines).
List<Map<String, dynamic>> speakingLines(Map<String, dynamic> content) {
  List<Map<String, dynamic>> list(Object? v) =>
      (v as List).cast<Map<String, dynamic>>();
  return [
    ...list(content['examiner']),
    for (final t in list(content['part1'])) ...[
      t['intro'] as Map<String, dynamic>,
      ...list(t['questions']),
    ],
    for (final c in list(content['part2'])) ...[
      c['topic'] as Map<String, dynamic>,
      c['roundingOff'] as Map<String, dynamic>,
      (c['part3'] as Map<String, dynamic>)['intro'] as Map<String, dynamic>,
      ...list((c['part3'] as Map<String, dynamic>)['questions']),
    ],
  ];
}

String _readme(List<Map<String, dynamic>> lines) {
  final b = StringBuffer()
    ..writeln('# Speaking examiner audio')
    ..writeln()
    ..writeln(
      'Original practice questions written for Bandwise; they are not IELTS '
      'questions. Every line the examiner says has a stable id in '
      '`content.json` and its own recording, `mp3/<id>.mp3`.',
    )
    ..writeln()
    ..writeln(
      '> Generated by `dart run tool/build_speaking_audio.dart --readme`. '
      'Edit content.json, then regenerate; do not edit this file by hand.',
    )
    ..writeln()
    ..writeln('## Engine and licences')
    ..writeln()
    ..writeln('| | |')
    ..writeln('| --- | --- |')
    ..writeln(
      '| Speech | Kokoro-82M (hexgrad), the `kokoro-en-v0_19` package run '
      'locally with sherpa-onnx |',
    )
    ..writeln(
      '| Licence | Apache-2.0 (Kokoro-82M weights; sherpa-onnx). Commercial '
      'use is allowed. |',
    )
    ..writeln(
      '| Voice | Built-in British male voice `bm_george`, speed 0.95. No '
      'voice is cloned. |',
    )
    ..writeln(
      '| Checking | Every take is transcribed with faster-whisper '
      '`Systran/faster-whisper-large-v3` (MIT) and must contain the '
      "script's words. It is only used to check takes; nothing from it is "
      'shipped. |',
    )
    ..writeln(
      '| Runtime | The Python environment bundled with VoiceStudio 0.5.6, '
      'called directly (not through its API), as for Listening |',
    )
    ..writeln()
    ..writeln(
      "VoiceStudio's default engine (OmniVoice) was not used: its model is "
      'licensed CC-BY-NC (non-commercial). See ../listening/README.md.',
    )
    ..writeln()
    ..writeln('## Rebuilding')
    ..writeln()
    ..writeln('```sh')
    ..writeln(
      '# 1. audio/<id>.wav for every line (resume-safe; --redo id,id to '
      'regenerate)',
    )
    ..writeln(
      '~/.config/VoiceStudio/runtime/project/.venv/bin/python '
      'tool/generate_speaking_voices.py',
    )
    ..writeln('# 2. mp3/<id>.mp3 (needs ffmpeg)')
    ..writeln('dart run tool/build_speaking_audio.dart')
    ..writeln('```')
    ..writeln()
    ..writeln(
      'The `audio/` folder is not committed; `mp3/` is. Recordings made by '
      'learners are never stored here: they stay on their device.',
    )
    ..writeln()
    ..writeln('## Lines')
    ..writeln()
    ..writeln('| # | Id | Text |')
    ..writeln('| --- | --- | --- |');
  for (final (i, l) in lines.indexed) {
    b.writeln(
      '| ${i + 1} | `${l['id']}` | '
      '${(l['text'] as String).replaceAll('|', r'\|')} |',
    );
  }
  return b.toString();
}
